@router.get("/signals")
async def get_signals(x_session_id: str = Header(alias="X-Session-ID")):
    """
    Get all trading signals.
    
    Returns active and expired signals from the database,
    falling back to mock data if database is unavailable.
    
    Args:
        x_session_id: Session ID from header for authentication
        
    Returns:
        List of trading signals with metadata
    """
    if not session_manager.validate_session(x_session_id):
        return {"error": "Not authenticated"}
    
    try:
        conn = get_db()
        c = conn.cursor()
        c.execute("SELECT * FROM signals ORDER BY triggered_at DESC LIMIT 50")
        rows = c.fetchall()
        conn.close()
        
        if rows:
            return [
                {
                    "id": row[0],
                    "symbol": row[1],
                    "signal_type": row[2],
                    "strategy": row[3],
                    "trigger_price": row[4],
                    "triggered_at": row[5],
                    "status": row[6],
                    "metadata": json.loads(row[7]) if row[7] else None
                }
                for row in rows
            ]
    except:
        pass
    
    return MOCK_SIGNALS
