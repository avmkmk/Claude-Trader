"""
Trading Signals Endpoints

Provides access to trading signals generated by strategies.
Signals can be stored in SQLite or returned as mock data.
"""

from fastapi import APIRouter, Header
from app.auth import session_manager
import sqlite3
import os
import json


# Create router with signals tag
router = APIRouter(tags=["signals"])


# Database path for signals storage
DB_PATH = os.path.join(os.path.dirname(os.path.dirname(__file__)), "..", "data", "dashboard.db")


def get_db():
    """
    Get a database connection with row factory.
    
    Returns:
        sqlite3.Connection: Database connection
    """
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn


